"""Synthesises the trailer score (pure Python, no dependencies): cinematic hybrid score in D minor, timed to the recorded shots.
Writes trailer_score.wav (44.1 kHz, 16-bit stereo). Original music generated by code: no samples, no licensed material."""
import array, math, random, sys, wave

SR = 44100
DUR = 53.4
N = int(SR * DUR)
L = array.array('f', [0.0]) * N
R = array.array('f', [0.0]) * N
random.seed(11)
TAU = 2 * math.pi
sin, exp = math.sin, math.exp


def smooth(x):
    x = 0.0 if x < 0 else 1.0 if x > 1 else x
    return x * x * (3 - 2 * x)


def add(start, dur, fn, gain=1.0, pan=0.0):
    i0 = int(start * SR); n = int(dur * SR)
    a = (pan + 1) * math.pi / 4; gl = gain * math.cos(a); gr = gain * math.sin(a)
    for i in range(n):
        j = i0 + i
        if j >= N: break
        s = fn(i / SR)
        L[j] += s * gl; R[j] += s * gr


def midi(n): return 440.0 * 2 ** ((n - 69) / 12.0)


# shot timeline (seconds): studio 0-3, aerial 3-20, day 20.5-27.5, sunset 27.9-32.9, night chase 33.4-42.4, top-down 42.4-45.4, finale 45.4-53.4
HITS = [(3.0, 0.45), (17.0, 0.85), (20.47, 0.5), (27.93, 0.5), (33.4, 0.9), (42.4, 0.7), (46.7, 1.0)]
RISERS = [(14.2, 17.0), (30.2, 33.4), (39.4, 42.4), (43.9, 46.7)]

print('sub drone + pad'); sys.stdout.flush()
def drone(t):
    env = smooth(t / 6.0) * smooth((50.5 - t) / 3.0)
    return env * (0.20 * sin(TAU * 36.71 * t) + 0.09 * sin(TAU * 73.42 * t + 0.5 * sin(TAU * 0.11 * t)))
add(0.5, 52.5, drone, 1.0)

CHORDS = [(62, 65, 69), (58, 62, 65), (65, 69, 72), (60, 64, 67)]   # Dm, Bb, F, C (triads, midi)
SEG = 6.4
for seg in range(8):
    start = 2.0 + seg * SEG
    chord = CHORDS[seg % 4]
    if start > 46.5: chord = (62, 66, 69)                              # D major resolution
    for nt in chord:
        f = midi(nt)
        for det, pan in ((0.996, -0.5), (1.004, 0.5)):
            f2 = f * det; ph = random.random() * TAU
            def pad(t, f2=f2, ph=ph, seg=seg):
                a = smooth(t / 2.2) * smooth((SEG + 1.6 - t) / 1.8)
                v = 0.0
                for h in (1, 2, 3, 4, 5):
                    v += sin(TAU * f2 * h * t + ph * h) / (h * h)
                return a * v * 0.030 * (0.6 + 0.4 * smooth((start + t - 3) / 14.0))
            add(start, SEG + 1.6, pad, 1.0, pan)

print('bass pulse'); sys.stdout.flush()
PAT = [38, 38, 41, 38, 45, 38, 41, 36]                                # D2 D2 F2 D2 A2 D2 F2 C2
def bass_note(t0, note, vol):
    f = midi(note)
    def b(t):
        e = exp(-t * 7.0)
        v = 0.0
        for h in (1, 2, 3, 4, 5, 6):
            v += sin(TAU * f * h * t) / h * exp(-t * (6 + 5 * h))
        return (v * 1.4 + sin(TAU * f * t) * 0.6) * e * vol
    add(t0, 0.28, b, 1.0, 0.0)
t = 20.47; k = 0
while t < 49.0:
    vol = 0.10 if t < 33.4 else 0.17 if t < 45.4 else 0.12
    if 27.5 < t < 27.93 or 32.9 < t < 33.4: t += 0.25; k += 1; continue
    bass_note(t, PAT[k % 8], vol); t += 0.25; k += 1

print('drums'); sys.stdout.flush()
def kick(t0, vol):
    def f(t):
        ph = TAU * (45 * t + 90 * (1 - exp(-t * 30)) / 30)
        return sin(ph) * exp(-t * 7) * vol
    add(t0, 0.5, f, 1.0)
def snare(t0, vol):
    def f(t): return (random.uniform(-1, 1) * exp(-t * 16) * 0.8 + sin(TAU * 190 * t) * exp(-t * 20) * 0.5) * vol
    add(t0, 0.35, f, 1.0, 0.1)
def hat(t0, vol, pan):
    prev = [0.0]
    def f(t):
        x = random.uniform(-1, 1); y = x - prev[0]; prev[0] = x
        return y * exp(-t * 70) * vol
    add(t0, 0.09, f, 1.0, pan)
b = 33.4; beat = 0
while b < 42.4:
    kick(b, 0.55);
    if beat % 2 == 1: snare(b, 0.30)
    for q in range(4): hat(b + q * 0.125, 0.07 if q % 2 == 0 else 0.04, -0.4 if q % 2 else 0.4)
    b += 0.5; beat += 1
for tt in (20.97, 21.97, 22.97, 23.97, 24.97, 25.97, 26.97):            # light taiko pulse in the day drive
    kick(tt, 0.22)
for tt in (28.4 + 0.5 * i for i in range(8)): kick(tt, 0.2)
for tt in (46.7, 47.2, 47.7): kick(tt, 0.6)

print('impacts'); sys.stdout.flush()
for (t0, vol) in HITS:
    def boom(t, vol=vol):
        ph = TAU * (28 * t + 70 * (1 - exp(-t * 4)) / 4)
        brass = 0.0
        for h in (1, 2, 3, 4, 5, 6, 7):
            brass += sin(TAU * 73.4 * h * t + 0.2 * h) / h
        return vol * (0.55 * sin(ph) * exp(-t * 1.5) + 0.16 * brass * exp(-t * 2.2) * smooth(t / 0.03) + random.uniform(-1, 1) * 0.35 * exp(-t * 6))
    add(t0, 3.2, boom, 1.0, 0.0)

print('risers'); sys.stdout.flush()
for (a, bb) in RISERS:
    st = [0.0]; d = bb - a
    def rise(t, d=d, st=st):
        u = min(1.0, t / d); al = 0.015 + 0.55 * u * u
        st[0] += al * (random.uniform(-1, 1) - st[0])
        tone = sin(TAU * (180 + 1500 * u * u) * t) * 0.25
        return (st[0] * 0.55 + tone * 0.35) * (u ** 2.2) * 0.65
    add(a, d + 0.02, rise, 1.0, 0.0)

print('rain, sirens, engine'); sys.stdout.flush()
st = [0.0]
def rain(t):
    st[0] += 0.22 * (random.uniform(-1, 1) - st[0]); return st[0] * 0.30 * smooth(t / 1.0) * smooth((9.0 - t) / 1.0)
add(33.4, 9.0, rain, 1.0, 0.0)
ph = [0.0]
def siren(t):
    f = 880 + 140 * sin(TAU * 0.85 * t); ph[0] += TAU * f / SR
    return sin(ph[0]) * 0.035 * smooth((t - 1.5) / 2.0) * smooth((6.5 - t) / 1.0) * (1 + 0.25 * sin(TAU * 0.85 * t))
add(35.9, 6.5, siren, 1.0, -0.6)
ph2 = [0.0]
def siren2(t):
    f = 700 + 120 * sin(TAU * 0.85 * t + 1.6); ph2[0] += TAU * f / SR
    return sin(ph2[0]) * 0.030 * smooth((t - 1.0) / 2.0) * smooth((5.5 - t) / 1.0)
add(36.9, 5.5, siren2, 1.0, 0.6)
def engine(f0, f1, dur):
    def e(t):
        u = t / dur; f = f0 + (f1 - f0) * u
        v = sum(sin(TAU * f * h * t) / h for h in (1, 2, 3)) * (0.7 + 0.3 * sin(TAU * 7 * t))
        return v * 0.030 * smooth(t / 0.4) * smooth((dur - t) / 0.4)
    return e
add(20.47, 7.0, engine(58, 92, 7.0), 1.0, 0.0)
add(27.93, 5.0, engine(70, 105, 5.0), 1.0, 0.0)
add(33.4, 12.0, engine(72, 120, 12.0), 1.0, 0.0)

print('finale chord'); sys.stdout.flush()
for nt, pan in ((50, -0.3), (57, 0.3), (62, -0.5), (66, 0.5), (69, 0.0), (74, 0.2)):
    f = midi(nt)
    def fin(t, f=f):
        vib = 1 + 0.003 * sin(TAU * 5.2 * t)
        v = sum(sin(TAU * f * vib * h * t) / h for h in (1, 2, 3, 4))
        return v * 0.045 * smooth(t / 1.2) * smooth((6.7 - t) / 3.0)
    add(46.7, 6.7, fin, 1.0, pan)

print('reverb + master'); sys.stdout.flush()
def reverb(buf, delays, fb, mix, damp=0.25):
    out = array.array('f', buf)
    wet = array.array('f', [0.0]) * N
    for d in delays:
        line = array.array('f', [0.0]) * d; idx = 0; lp = 0.0
        for i in range(N):
            y = line[idx]; lp = lp + damp * (y - lp) if False else y * (1 - damp) + lp * damp
            line[idx] = buf[i] + lp * fb
            wet[i] += y
            idx += 1
            if idx == d: idx = 0
    g = mix / len(delays)
    for i in range(N): out[i] = buf[i] + wet[i] * g
    return out
L2 = reverb(L, (1557, 1617, 1491, 1422, 1277, 1356, 2113), 0.82, 0.9)
R2 = reverb(R, (1580, 1640, 1517, 1447, 1297, 1379, 2137), 0.82, 0.9)

import vo_mix
VD, VL, VR = vo_mix.build(N, SR)
peak = max(max(abs(x) for x in L2), max(abs(x) for x in R2))
scale = 0.89 / peak
fade_in = int(0.4 * SR); fade_out = int(2.2 * SR)
data = array.array('h', [0]) * (2 * N)
for i in range(N):
    g = scale
    if i < fade_in: g *= i / fade_in
    if i > N - fade_out: g *= (N - i) / fade_out
    data[2 * i] = int(max(-1.0, min(1.0, L2[i] * g * VD[i] + VL[i])) * 32767)
    data[2 * i + 1] = int(max(-1.0, min(1.0, R2[i] * g * VD[i] + VR[i])) * 32767)
out = sys.argv[1] if len(sys.argv) > 1 else 'trailer_score.wav'
with wave.open(out, 'wb') as w:
    w.setnchannels(2); w.setsampwidth(2); w.setframerate(SR); w.writeframes(data.tobytes())
print('wrote', out, round(N / SR, 2), 's, peak scale', round(scale, 3))
